import { WARD_ROWS, WARDS_AS_OF } from "./wards"

/**
 * Where people are, in the units on today's addresses.
 *
 * Since 1 July 2025 Vietnam has two levels of local government: a province or
 * city, then the phường / xã / đặc khu. There are no quận or huyện any more, so
 * an address reads "12 Lê Lợi, Phường Sài Gòn, TP.HCM". The `district` field
 * everywhere (database columns, types) holds that commune-level unit; the name
 * stayed so rows saved before the reform keep working.
 *
 * TP.HCM now includes the former Bình Dương and Bà Rịa - Vũng Tàu, and Đà Nẵng
 * the former Quảng Nam: the wards cover that whole ground. lib/wards.ts is
 * generated by scripts/gen-wards.ts (sources in scripts/data/wards-2026.json).
 */
export { WARDS_AS_OF }

export interface Ward {
  /** With its type, as on an address: "Phường Sài Gòn", "Xã Sóc Sơn", "Đặc khu Côn Đảo". */
  name: string
  lat: number
  lng: number
  /** What it was formed from, so "Quận 1" or "Bến Nghé" still finds it. */
  formerly: string
}

export const WARDS: Record<string, Ward[]> = Object.fromEntries(
  Object.entries(WARD_ROWS).map(([city, rows]) => [city, rows.map(([name, lat, lng, formerly]) => ({ name, lat, lng, formerly }))]),
)

