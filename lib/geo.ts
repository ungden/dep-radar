/** Every place a row may name, today's wards and the old districts, with its centre. */
export const DISTRICT_COORDS: Record<string, Record<string, [number, number]>> = Object.fromEntries(
  Object.keys(WARDS).map((city) => [
    city,
    { ...LEGACY_DISTRICTS[city], ...Object.fromEntries(WARDS[city].map((w) => [w.name, [w.lat, w.lng] as [number, number]])) },
  ]),
)

export const CITIES = Object.keys(WARDS)
/** The wards of a city a picker offers, by name. */
export const districtsOf = (city: string) => (WARDS[city] ?? []).map((w) => w.name)
/** A name saved before the reform (a quận / huyện), which a picker no longer offers. */
export const isLegacyDistrict = (city: string, district: string) => Boolean(LEGACY_DISTRICTS[city]?.[district]) && !districtsOf(city).includes(district)

/** A point on the map, [latitude, longitude]. */
export type LatLng = [number, number]

/** Roads are not straight lines: the straight distance times this is the estimate. */
export const ROAD_FACTOR = 1.35
/**
 * The shortest distance we quote. Without a pin a person's point is their
 * ward's centre, so anything closer than this would be precision we do not have.
 */
export const MIN_ROAD_KM = 2

function straightKm(a: LatLng, b: LatLng) {
  const R = 6371
  const toRad = (d: number) => (d * Math.PI) / 180
  const dLat = toRad(b[0] - a[0])
  const dLng = toRad(b[1] - a[1])
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a[0])) * Math.cos(toRad(b[0])) * Math.sin(dLng / 2) ** 2
  return 2 * R * Math.asin(Math.sqrt(h))
}

const roadKm = (a: LatLng, b: LatLng) => Math.round(straightKm(a, b) * ROAD_FACTOR * 10) / 10

export const districtPoint = (city: string, district: string): LatLng | null => DISTRICT_COORDS[city]?.[district] ?? null

/** Distance in km on the road between two districts (null when in different cities). */
export function travelDistanceKm(fromCity: string, fromDistrict: string, toCity: string, toDistrict: string): number | null {
  if (fromCity !== toCity) return null
  const a = districtPoint(fromCity, fromDistrict)
  const b = districtPoint(toCity, toDistrict)
  if (!a || !b) return null
  if (fromDistrict === toDistrict) return MIN_ROAD_KM
  return roadKm(a, b)
}

export const isLatLng = (value: unknown): value is LatLng =>
  Array.isArray(value) &&
  value.length === 2 &&
  value.every((n) => typeof n === "number" && Number.isFinite(n)) &&
  Math.abs(value[0]) <= 90 &&
  Math.abs(value[1]) <= 180

/**
 * How far from the nearest ward centre a point can be and still count as in
 * that city. Wards are a few km across in town and wider in the country, so
 * this is generous. The offshore special zones (Côn Đảo, Hoàng Sa) are not in
 * the list at all: nobody can travel there for a booking.
 */
export const CITY_REACH_KM = 15

/** The ward a point is in, as near as centres tell: the nearest one, if close enough. */
export function wardOfPoint(point: LatLng): { city: string; district: string } | null {
  if (!isLatLng(point)) return null
  let best: { city: string; district: string; km: number } | null = null
  for (const [city, wards] of Object.entries(WARDS)) {
    for (const w of wards) {
      const km = straightKm(point, [w.lat, w.lng])
      if (!best || km < best.km) best = { city, district: w.name, km }
    }
  }
  return best && best.km <= CITY_REACH_KM ? { city: best.city, district: best.district } : null
}

/** The city a point is in: the one with the nearest ward centre, if it is close enough. */
export const cityOfPoint = (point: LatLng): string | null => wardOfPoint(point)?.city ?? null

/** A place said in full for search: the ward and what it was formed from, so "quận 1" still finds it. */
export const placeWords = (city: string, district: string) =>
  [district, (WARDS[city] ?? []).find((w) => w.name === district)?.formerly ?? "", city].join(" ")

/** Lower case, no marks: "Phường Bến Thành" matches "ben thanh". */
const fold = (text: string) =>
  text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")

/**
 * The wards of a city matching what someone typed, by today's name or by what
 * it was formed from ("quan 1", "ben nghe", "thu dau mot"). The type word is
 * optional: "sai gon" finds "Phường Sài Gòn". Names first, then the former units.
 */
export function searchWards(city: string, query: string): Ward[] {
  const wards = WARDS[city] ?? []
  // "q1", "q.1" are how people type Quận 1.
  const words = fold(query)
    .replace(/\bq\.?\s*(\d+)\b/g, "quan $1")
    .split(/[^a-z0-9]+/)
    .filter(Boolean)
  if (!words.length) return wards
  // The words run together in the place, each starting a word of it; a number
  // is the whole number ("quận 1" is not Quận 10, nor "Phường 1" of another quận).
  const same = (w: string, t: string) => (/^\d+$/.test(w) ? t === w : t.startsWith(w))
  const hits = (text: string) => {
    const tokens = fold(text).split(/[^a-z0-9]+/)
    return tokens.some((_, i) => words.every((w, j) => tokens[i + j] !== undefined && same(w, tokens[i + j])))
  }
  const byName = wards.filter((w) => hits(w.name))
  const byFormer = wards.filter((w) => !byName.includes(w) && hits(`${w.name} ${w.formerly}`))
  return [...byName, ...byFormer]
}

/**
 * Distance in km on the road from a raw point (the customer's own location)
 * to a district, with the same road factor and floor as `travelDistanceKm`.
 * Null when the district is not on the map or the point is in another city,
 * as `travelDistanceKm` is between cities.
 */
export function distanceFromPointKm(point: LatLng, toCity: string, toDistrict: string): number | null {
  if (!isLatLng(point)) return null
  const b = districtPoint(toCity, toDistrict)
  if (!b || cityOfPoint(point) !== toCity) return null
  return Math.max(MIN_ROAD_KM, roadKm(point, b))
}
