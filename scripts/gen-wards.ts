/**
 * Emits lib/wards.ts and the districts upserts from scripts/data/wards-2026.json,
 * the commune-level units (phường / xã) of the three cities after the 2025
 * reform, with a centre for each and what it was formed from.
 *
 *   npx tsx scripts/gen-wards.ts            # regenerate lib/wards.ts
 *   npx tsx scripts/gen-wards.ts --sql      # print the districts upserts for a migration
 *
 * Offshore special zones (serviceable: false) are left out: nobody travels
 * there for a booking, and a point near the coast must not match them.
 */
import { readFileSync, writeFileSync } from "node:fs"

interface Unit {
  code?: string
  name: string
  type?: string
  lat: number
  lng: number
  formerly?: string
  formerDistricts?: string[]
  approx?: boolean
  serviceable?: boolean
}
interface Source {
  asOf: string
  sources: { title: string; url: string }[]
  provinces: Record<string, Unit[]>
}

const CITIES = ["Hà Nội", "TP.HCM", "Đà Nẵng"]
const data = JSON.parse(readFileSync("scripts/data/wards-2026.json", "utf8")) as Source
const q = (s: string) => `'${s.replace(/'/g, "''")}'`
const round = (n: number) => Math.round(n * 1e4) / 1e4

/** "Phường Bến Thành" sorts under B: people look a ward up by its name, not its type. */
const bare = (name: string) => name.replace(/^(Phường|Xã|Đặc khu) /, "")

const cities = CITIES.map((city) => {
  const units = (data.provinces[city] ?? [])
    .filter((u) => u.serviceable !== false)
    .sort((a, b) => bare(a.name).localeCompare(bare(b.name), "vi") || a.name.localeCompare(b.name, "vi"))
  if (!units.length) throw new Error(`no wards for ${city}`)
  const names = new Set<string>()
  for (const u of units) {
    if (names.has(u.name)) throw new Error(`${city}: ${u.name} twice`)
    names.add(u.name)
    if (!Number.isFinite(u.lat) || !Number.isFinite(u.lng)) throw new Error(`${city}: ${u.name} has no centre`)
  }
  return { city, units }
})

const formerly = (u: Unit) => (u.formerly ?? (u.formerDistricts ?? []).join(", ")).replace(/\s+/g, " ").trim()

if (process.argv.includes("--sql")) {
  let order = 1000
  for (const { city, units } of cities)
    for (const u of units)
      console.log(
        `insert into public.districts (city, district, lat, lng, sort_order) values (${q(city)}, ${q(u.name)}, ${round(u.lat)}, ${round(u.lng)}, ${order++})\n` +
          "  on conflict (city, district) do update set lat = excluded.lat, lng = excluded.lng, sort_order = excluded.sort_order;",
      )
} else {
  const out = [
    "// Generated by scripts/gen-wards.ts from scripts/data/wards-2026.json. Do not edit by hand.",
    `// Commune-level units after the 1 July 2025 reform, as of ${data.asOf}.`,
    "// Sources:",
    ...data.sources.map((s) => `//   ${s.title}: ${s.url}`),
    "",
    `export const WARDS_AS_OF = ${JSON.stringify(data.asOf)}`,
    "",
    "/** [name, lat, lng, what it was formed from] per city, by name (the type word aside). */",
    "export const WARD_ROWS: Record<string, [string, number, number, string][]> = {",
    ...cities.flatMap(({ city, units }) => [
      `  ${JSON.stringify(city)}: [`,
      ...units.map((u) => `    [${JSON.stringify(u.name)}, ${round(u.lat)}, ${round(u.lng)}, ${JSON.stringify(formerly(u))}],`),
      "  ],",
    ]),
    "}",
    "",
  ]
  writeFileSync("lib/wards.ts", out.join("\n"))
  console.log(cities.map(({ city, units }) => `${city}: ${units.length}`).join(", "))
}
